const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function copyProjectLicense(context) {
  const sourcePath = path.join(context.packager.projectDir, 'LICENSE');
  // On macOS the packaged resources live inside the app bundle, not in a
  // top-level resources/ directory next to it.
  const resourcesDir =
    context.electronPlatformName === 'darwin'
      ? path.join(
          context.appOutDir,
          `${context.packager.appInfo.productFilename}.app`,
          'Contents',
          'Resources'
        )
      : path.join(context.appOutDir, 'resources');
  const destinationPath = path.join(resourcesDir, 'LICENSE.txt');
  fs.mkdirSync(resourcesDir, { recursive: true });
  fs.copyFileSync(sourcePath, destinationPath);
  return destinationPath;
}

module.exports = async function afterPackMacAdhocSign(context) {
  // Keep the project's own MIT notice alongside the app on every platform. Dependency and
  // Electron notices generated by the packager do not replace the application's license.
  copyProjectLicense(context);

  if (context.electronPlatformName !== 'darwin') {
    return;
  }

  // electron-builder creates unsigned x64/arm64 temporary apps before merging a
  // universal build. Ad-hoc signing those intermediates changes CodeResources and
  // makes the merge fail. The hook runs again for the final universal app. This
  // signature protects bundle integrity only; it is not Apple Developer-ID signing
  // and the resulting artifact is not notarized.
  if (/mac-universal-(?:x64|arm64)-temp$/.test(context.appOutDir)) {
    return;
  }

  const productFilename = context.packager.appInfo.productFilename;
  const appPath = path.join(context.appOutDir, `${productFilename}.app`);

  execFileSync('codesign', ['--force', '--deep', '--sign', '-', appPath], {
    stdio: 'inherit',
  });

  execFileSync('codesign', ['--verify', '--deep', '--strict', '--verbose=4', appPath], {
    stdio: 'inherit',
  });
};

module.exports.copyProjectLicense = copyProjectLicense;
